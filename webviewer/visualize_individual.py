def update(frame_idx):
    # only declare globals that are assigned in this function to satisfy linters
    global ln_env, ln_fitness_marker, abs_bar_patches
    i = int(frame_idx)
    # update called for frame i
    env_idx, env_res = env_list[i]
    ind = ind_list[i]
    pop = len(ind.get("ids", []))
    # select chosen individual id in this frame (if present)
    if len(ind["ids"]) == 0:
        marker.set_data([], [])
        ax_nn.clear()
        ax_nn.axis("off")
        ax_nn.text(0.5, 0.5, "no individuals in this frame", ha="center", va="center")
        return
    # find index of selected_id in current frame
    if selected_id in ind["ids"]:
        sel_index = ind["ids"].index(selected_id)
        pos = ind["pos"][sel_index]
        resources = ind["resources"][sel_index]
        spend = ind["spend"][sel_index]
        delta = ind["delta"][sel_index]
        absent = False
    else:
        # chosen id not present in this frame
        marker.set_data([], [])
        ax_nn.clear()
        ax_nn.axis("off")
        ax_nn.text(
            0.5,
            0.5,
            f"selected id {selected_id} not present at t={times[i]}",
            ha="center",
            va="center",
        )
        absent = True
        return
    # update env plot marker and animate the environment line itself
    marker.set_data([pos], [env_res[pos]])
    # update environment line: redraw density-aware LineCollection for this frame
    try:
        try:
            if ln_env is not None:
                # LineCollection supports remove()
                ln_env.remove()
        except Exception:
            # fallback: clear collections from axis
            try:
                ax_env.collections.clear()
            except Exception:
                pass
        # draw new density-aware environment line using current individuals positions
        ln_env = draw_env_with_density(ax_env, env_idx, env_res, positions=ind.get('pos', []))
    except Exception:
        # fallback to simple line plot
        try:
            ln_env = ax_env.plot(env_idx, env_res, label="resource")
        except Exception:
            pass
    ax_env.set_ylim(0, max(env_global_max * 1.2, 1.0))
    ax_env.set_title(
        f'Environment (t={times[i]}) - ind {ind["ids"][sel_index]} '
        f'pos={pos} res={resources:.2f} pop={pop}'
    )
    ax_env.set_xlabel("position")
    ax_env.set_ylabel("resource")

    # update NN text if present and individual exists
    if not absent:
        # attempt to get NN from index mapping
        ind_nn = None
        if nn_index is not None and selected_id is not None:
            key = str(selected_id)
            if key in nn_index:
                ind_nn = nn_index[key]
        use_nn = ind_nn
        if use_nn is None:
            ax_nn.clear()
            ax_nn.axis("off")
            ax_nn.text(
                0.5,
                0.5,
                "NN json not found (global or per-individual)",
                ha="center",
                va="center",
            )
        else:
            # compute local neighborhood input vector: left, center, right, occupancy
            env_w = len(env_res)
            left_idx = (pos - 1) % env_w
            right_idx = (pos + 1) % env_w
            left_val = float(env_res[left_idx]) if left_idx < len(env_res) else 0.0
            center_val = float(env_res[pos]) if pos is not None and pos < len(env_res) else 0.0
            right_val = float(env_res[right_idx]) if right_idx < len(env_res) else 0.0
            # occupancy: count individuals at this position in current frame
            try:
                occupancy = int(np.sum(ind.get("pos", []) == pos))
            except Exception:
                occupancy = 0

            # include individual's internal resources as an extra input to match C++ Individual::act
            input_vec = [left_val, center_val, right_val, float(occupancy), float(resources)]

            # compute local forward for display using the loaded nn (vector-aware)
            direction, magnitude = g_nn.forward_single_with_nn(input_vec, use_nn)
            # compute full output vector and scalar output value
            output_vec = g_nn.compute_output_vector(use_nn, input_vec)
            try:
                output_val = float(np.asarray(output_vec).flatten()[0])
            except Exception:
                output_val = 0.0
            # compute fitness: individual's resource divided by
            #                  total resources of population in this frame
            try:
                total_resources = float(np.sum(ind.get("resources", [])))
                fitness = (
                    float(resources) / total_resources if total_resources > 0 else 0.0
                )
            except Exception:
                fitness = 0.0
            # update resources histogram for this time-frame
            try:
                cur_abs = (
                    abs_fitness_by_frame[i]
                    if i < len(abs_fitness_by_frame)
                    else np.array([])
                )
                new_abs_counts = (
                    np.histogram(cur_abs, bins=bins)[0]
                    if cur_abs.size > 0
                    else np.zeros(len(bins) - 1, dtype=int)
                )
                abs_bar_patches, ln_fitness_marker = g_rf.update_fitness_axis(
                    ax_fitness,
                    abs_bar_patches,
                    ln_fitness_marker,
                    new_abs_counts,
                    resources,
                    bins,
                    max_count,
                    times[i],
                )
            except Exception:
                pass
            # draw network graph (prefer graphs_nn module if available)
            try:
                g_nn.draw_nn_graph(ax_nn, use_nn, output_val=output_val)
            except Exception:
                ax_nn.clear()
                ax_nn.axis("off")
                ax_nn.text(0.5, 0.5, "NN render error", ha="center", va="center")
            # prepare nearby resource vector (2 left, pos, 2 right)
            # previous L/r0/r1 were unused and removed
            # local scalar resource value
            existence = existence_map.get(selected_id, None)
            curtime = times[i]
            # compute fitness rank percentile within this frame's rel_fitness distribution
            fitness_rank_pct = None
            try:
                if i < len(rel_fitness_by_frame):
                    rel_arr = rel_fitness_by_frame[i]
                    if rel_arr.size > 0:
                        # use the individual's relative fitness value from rel_arr when possible
                        try:
                            indiv_rel = float(rel_arr[sel_index]) if sel_index < len(rel_arr) else float(fitness)
                        except Exception:
                            indiv_rel = float(fitness)
                        less = float(np.sum(rel_arr < indiv_rel))
                        equal = float(np.sum(rel_arr == indiv_rel))
                        fitness_rank_pct = 100.0 * (less + 0.5 * equal) / float(len(rel_arr))
            except Exception:
                fitness_rank_pct = None

            # show center value as the local_input in the info box
            local_input_val = center_val if pos is not None else None

            # render info box via graphs_nn if available
            try:
                # we intentionally do NOT pass a position-percentile here; the
                # parenthetical percentile should display next to relative
                # fitness instead (fitness_rank_pct)
                g_nn.draw_info(
                    ax_nn,
                    ax_info,
                    use_nn=use_nn,
                    spend=spend,
                    delta=delta,
                    resources=resources,
                    output_vec=output_vec,
                    fitness=fitness,
                    fitness_rank_pct=fitness_rank_pct,
                    existence=existence,
                    current_time=curtime,
                    times=times,
                    pos=pos,
                    pos_percentile=None,
                    pop=pop,
                    local_input=local_input_val,
                )
            except Exception:
                pass
                pass

    # update response curve using the selected individual's NN (or global fallback)
    # compute multiple scenario response curves by varying the center input
    # while keeping left/right/occupancy fixed. Scenarios:
    #  - peak: center varies, left/right fixed at measured values
    #  - slope→: center varies but weight shift to right (we simulate by using right-shifted inputs)
    #  - slope←: center varies but weight shift to left
    #  - sink: center varies but we invert sign (simulate sink by negating inputs)
    #  - flat: center varies but neighbors set to same constant (flat landscape)
    try:
        # prepare constant neighbor and occupancy values
        left_const = left_val
        right_const = right_val
        occ_const = float(occupancy)
        # helper to make an input vector for given center value
        def make_input(cval, l=left_const, r=right_const, o=occ_const, res_val=float(resources)):
            # build vector with left, center, right, occupancy, internal resources
            if use_nn is None:
                return [l, cval, r, o, res_val]
            # respect nn_use_occupancy if present in the nn dict
            try:
                nn_use_occ = True
                if isinstance(use_nn, dict) and "nn_use_occupancy" in use_nn:
                    nn_use_occ = bool(use_nn.get("nn_use_occupancy", True))
            except Exception:
                nn_use_occ = True
            vec = [l, cval, r]
            if nn_use_occ:
                vec.append(o)
            # always append individual's internal resources as last input
            vec.append(res_val)
            return vec

        ys_peak = g_nn.compute_nn_response_for(xs, use_nn, input_builder=lambda xval: make_input(xval))
        # slope right: use center values but bias inputs to the right by mixing towards right_const
        ys_slope_r = g_nn.compute_nn_response_for(xs, use_nn, input_builder=lambda xval: make_input(xval, l=(left_const + right_const) / 2.0, r=right_const))
        # slope left: bias towards left
        ys_slope_l = g_nn.compute_nn_response_for(xs, use_nn, input_builder=lambda xval: make_input(xval, l=left_const, r=(left_const + right_const) / 2.0))
        # sink: invert center magnitude to simulate sink-like response
        ys_sink = g_nn.compute_nn_response_for(xs, use_nn, input_builder=lambda xval: make_input(-xval, l=left_const, r=right_const))
        # flat: neighbors equal to center value (flat landscape)
        ys_flat = g_nn.compute_nn_response_for(xs, use_nn, input_builder=lambda xval: make_input(xval, l=xval, r=xval))

        # now compute 'full occupancy' variants with occupancy forced to a large number (1000)
        FULL_OCC = 1000.0
        ys_peak_full = g_nn.compute_nn_response_for(xs, use_nn, input_builder=lambda xval: make_input(xval, o=FULL_OCC))
        ys_slope_r_full = g_nn.compute_nn_response_for(xs, use_nn, input_builder=lambda xval: make_input(xval, l=(left_const + right_const) / 2.0, r=right_const, o=FULL_OCC))
        ys_slope_l_full = g_nn.compute_nn_response_for(xs, use_nn, input_builder=lambda xval: make_input(xval, l=left_const, r=(left_const + right_const) / 2.0, o=FULL_OCC))
        ys_sink_full = g_nn.compute_nn_response_for(xs, use_nn, input_builder=lambda xval: make_input(-xval, l=left_const, r=right_const, o=FULL_OCC))
        ys_flat_full = g_nn.compute_nn_response_for(xs, use_nn, input_builder=lambda xval: make_input(xval, l=xval, r=xval, o=FULL_OCC))

        ys_display_dict = {
            "peak": np.abs(ys_peak) if resp_abs_mode.get("val", False) else ys_peak,
            "slope_r": np.abs(ys_slope_r) if resp_abs_mode.get("val", False) else ys_slope_r,
            "slope_l": np.abs(ys_slope_l) if resp_abs_mode.get("val", False) else ys_slope_l,
            "sink": np.abs(ys_sink) if resp_abs_mode.get("val", False) else ys_sink,
            "flat": np.abs(ys_flat) if resp_abs_mode.get("val", False) else ys_flat,
            # full occupancy variants
            "peak_full": np.abs(ys_peak_full) if resp_abs_mode.get("val", False) else ys_peak_full,
            "slope_r_full": np.abs(ys_slope_r_full) if resp_abs_mode.get("val", False) else ys_slope_r_full,
            "slope_l_full": np.abs(ys_slope_l_full) if resp_abs_mode.get("val", False) else ys_slope_l_full,
            "sink_full": np.abs(ys_sink_full) if resp_abs_mode.get("val", False) else ys_sink_full,
            "flat_full": np.abs(ys_flat_full) if resp_abs_mode.get("val", False) else ys_flat_full,
        }
    except Exception:
        # If computing the scenario-specific curves fails, avoid falling back
        # to a single identical curve unless the network is truly a 1-node
        # single-input network. In that special case the single-curve is a
        # reasonable representation. For other networks, return NaN arrays
        # so the response plot remains blank (avoids misleading identical curves).
        fallback_allowed = False
        try:
            if use_nn is not None and isinstance(use_nn, dict):
                w = use_nn.get("weights", [])
                b = use_nn.get("biases", [])
                # single node and single scalar-weight layout: weights is list of scalars of length 1
                if len(w) == 1 and not hasattr(w[0], "__iter__"):
                    fallback_allowed = True
        except Exception:
            fallback_allowed = False

        if fallback_allowed:
            ys = g_nn.compute_nn_response_for(xs, use_nn)
            ys_display_dict = {
                "peak": np.abs(ys) if resp_abs_mode.get("val", False) else ys,
                "slope_r": np.abs(ys) if resp_abs_mode.get("val", False) else ys,
                "slope_l": np.abs(ys) if resp_abs_mode.get("val", False) else ys,
                "sink": np.abs(ys) if resp_abs_mode.get("val", False) else ys,
                "flat": np.abs(ys) if resp_abs_mode.get("val", False) else ys,
                # full occupancy variants (same single-curve fallback)
                "peak_full": np.abs(ys) if resp_abs_mode.get("val", False) else ys,
                "slope_r_full": np.abs(ys) if resp_abs_mode.get("val", False) else ys,
                "slope_l_full": np.abs(ys) if resp_abs_mode.get("val", False) else ys,
                "sink_full": np.abs(ys) if resp_abs_mode.get("val", False) else ys,
                "flat_full": np.abs(ys) if resp_abs_mode.get("val", False) else ys,
            }
        else:
            nan_arr = np.full_like(xs, np.nan)
            ys_display_dict = {
                "peak": nan_arr,
                "slope_r": nan_arr,
                "slope_l": nan_arr,
                "sink": nan_arr,
                "flat": nan_arr,
                "peak_full": nan_arr,
                "slope_r_full": nan_arr,
                "slope_l_full": nan_arr,
                "sink_full": nan_arr,
                "flat_full": nan_arr,
            }

    # update response axis via helper module
    try:
        n_nodes = 0
        if use_nn is not None:
            n_nodes = max(len(use_nn.get("weights", [])), len(use_nn.get("biases", [])))
        curr_x = float(env_res[pos])
        g_rf.update_response_axis(
            ax_resp,
            ln_resp,
            ln_input_vline,
            ln_input_dot,
            xs,
            ys_display_dict,
            curr_x,
            resp_abs_mode.get("val", False),
            n_nodes,
        )
    except Exception:
        # best-effort fallback inline update using the dict of scenario curves
        try:
            if isinstance(ln_resp, (list, tuple)) and len(ln_resp) == 5:
                rep = ys_display_dict.get("peak", None)
                if rep is None:
                    rep = next(iter(ys_display_dict.values()))
                ln_resp[0].set_ydata(ys_display_dict.get("peak", rep))
                ln_resp[1].set_ydata(ys_display_dict.get("slope_r", rep))
                ln_resp[2].set_ydata(ys_display_dict.get("slope_l", rep))
                ln_resp[3].set_ydata(ys_display_dict.get("sink", rep))
                ln_resp[4].set_ydata(ys_display_dict.get("flat", rep))
            else:
                rep = ys_display_dict.get("peak", None)
                if rep is None:
                    rep = next(iter(ys_display_dict.values()))
                ln_resp.set_ydata(rep)
        except Exception:
            pass
        try:
            curr_x = float(env_res[pos])
            ln_input_vline.set_xdata([curr_x, curr_x])
            rep = ys_display_dict.get("peak", None) if isinstance(ys_display_dict, dict) else ys_display_dict
            ln_input_dot.set_data([curr_x], [np.interp(curr_x, xs, rep)])
        except Exception:
            pass
        n_nodes = 0
        if use_nn is not None:
            n_nodes = max(len(use_nn.get("weights", [])), len(use_nn.get("biases", [])))
        y_margin = 0.1
        y_lim = max(1.0, n_nodes)
        if resp_abs_mode.get("val", False):
            ax_resp.set_ylim(0 - y_margin, y_lim + y_margin)
        else:
            ax_resp.set_ylim(-y_lim - y_margin, y_lim + y_margin)
        ax_resp.relim()
        ax_resp.autoscale_view(False)

    fig.canvas.draw_idle()


update(0)
