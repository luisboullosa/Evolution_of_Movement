def step_selected(delta):
    """Step selection through sorted all_ids by delta (-1 or 1).

    This remains available but Prev/Next buttons now prefer frame-local
    stepping (see step_selected_in_frame). This function is preserved for
    compatibility with other potential callers.
    """
    global selected_id
    if not all_ids:
        return
    try:
        # find current index in all_ids; if current selected_id not present, pick 0
        idx = all_ids.index(selected_id) if selected_id in all_ids else 0
    except Exception:
        idx = 0
    idx = max(0, min(len(all_ids) - 1, idx + int(delta)))
    selected_id = all_ids[idx]
    try:
        txtbox.set_val(str(selected_id))
    except Exception:
        pass
    try:
        update(slider.val)
    except Exception:
        pass


def step_selected_in_frame(delta):
    """Step selection through individuals present in the current frame only.

    This is used by the Prev/Next buttons so arrows cycle through "live"
    individuals at the displayed timepoint.
    """
    global selected_id
    try:
        cur = int(slider.val)
        ids = ind_list[cur].get("ids", [])
        if not ids:
            return
        # if selected_id present use its index, otherwise start at 0
        try:
            idx = ids.index(selected_id) if selected_id in ids else 0
        except Exception:
            idx = 0
        # advance and wrap around within the current frame's IDs
        idx = (idx + int(delta)) % len(ids)
        selected_id = ids[idx]
        try:
            txtbox.set_val(str(selected_id))
        except Exception:
            pass
        try:
            update(slider.val)
        except Exception:
            pass
    except Exception:
        # fallback to global stepping if anything goes wrong
        try:
            step_selected(delta)
        except Exception:
            pass


def on_prev(event):
    # prefer stepping through individuals present in the current frame
    step_selected_in_frame(-1)


def on_next(event):
    # prefer stepping through individuals present in the current frame
    step_selected_in_frame(1)


def on_rand(event):
    global selected_id
    # pick a random individual present in the current frame
    try:
        i = int(slider.val)
        ind = ind_list[i]
        if len(ind["ids"]) == 0:
            return
        selected_id = random.choice(ind["ids"])
        try:
            txtbox.set_val(str(selected_id))
        except Exception:
            pass
        update(slider.val)
    except Exception:
        pass


def anim_step():
    # advance frames while playing; stop at final frame instead of wrapping
    if playing.get("val", False):
        try:
            cur = int(slider.val)
            if cur < n_frames - 1:
                slider.set_val(cur + 1)
            else:
                # reached the last frame: stop playing and timer
                playing["val"] = False
                try:
                    if timer is not None:
                        timer.stop()
                except Exception:
                    pass
                try:
                    btn.label.set_text("Play")
                except Exception:
                    pass
        except Exception:
            pass


